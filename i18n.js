  // ===== 引擎 =====
  const els = document.querySelectorAll('[data-i18n]');
  const zh = {};
  els.forEach(el => { zh[el.dataset.i18n] = el.innerHTML; });
  const altEls = document.querySelectorAll('[data-i18n-alt]');
  const zhAlt = {};
  altEls.forEach(el => { zhAlt[el.dataset.i18nAlt] = el.alt; });

  // title / meta description 抓取（子页用 data-i18n-title / data-i18n-desc，否则回退全局 meta.title/meta.desc）
  const titleEl = document.querySelector('[data-i18n-title]') || document.querySelector('title');
  const descEl = document.querySelector('meta[name="description"][data-i18n-desc]') || document.querySelector('meta[name="description"]');
  const zhTitle = titleEl.text || document.title;
  const zhDesc = descEl.content || '';

  const btn = document.getElementById('langSwitch');

  let lang = localStorage.getItem('qagent-lang') || 'zh';

  function apply(l) {
    lang = l;
    document.documentElement.lang = l === 'en' ? 'en' : 'zh-CN';
    els.forEach(el => {
      const k = el.dataset.i18n;
      el.innerHTML = l === 'en' ? (en[k] ?? zh[k]) : zh[k];
    });
    altEls.forEach(el => {
      const k = el.dataset.i18nAlt;
      el.alt = l === 'en' ? (en[k] ?? zhAlt[k]) : zhAlt[k];
    });
    // 标题：子页用子页键，否则回退到全局 meta.title
    const titleKey = titleEl.dataset.i18nTitle;
    const descKey = descEl.dataset.i18nDesc;
    document.title = l === 'en'
      ? (titleKey ? (en[titleKey] ?? zhTitle) : (en['meta.title'] ?? zhTitle))
      : zhTitle;
    descEl.content = l === 'en'
      ? (descKey ? (en[descKey] ?? zhDesc) : (en['meta.desc'] ?? zhDesc))
      : zhDesc;
    btn.textContent = l === 'en' ? '中文' : 'EN';
    localStorage.setItem('qagent-lang', l);
  }

  btn.addEventListener('click', () => apply(lang === 'en' ? 'zh' : 'en'));

  // 供 main.js 使用的接口
  window.QI18N = {
    tip: key => tips[key][lang],
    copied: () => copiedLabel[lang],
    copyLabel: () => (lang === 'en' ? 'Copy' : '复制')
  };

  if (lang === 'en') apply('en');
